export interface Todo {
  id: string;
  text: string;
  description?: string;
  completed: boolean;
  createdAt: Date;
  completedAt?: Date;
  deadline?: Date;
  reminder?: Date;
  recurring?: "none" | "daily" | "weekly" | "monthly";
  listId: string;
}

export interface UserProfile {
  id: string;
  email: string;
  username: string;
  name?: string;
  verified: boolean;
  avatar?: string;
}

export interface PocketBaseTaskListRecord {
  id?: string; // Optional, autogenerated if not set
  user_id: string; // Required, relation record id
  createdAt: string; // Required
  yjsUpdate?: string; // Optional, plain text value
  yjsClientId?: string; // Optional, plain text value
  deleted?: boolean;
}

export interface PocketBasePermissionsRecord {
  id?: string; // Optional 
  task_list: string; // Relation record id
  user_id: string;  // Relation record id
  invited_by: string; // Relation record id
  status: string; // invited | active | rejected
  permission: string; // edit | view
  inviter_email: string; // Email of user that created the invite
  expand?: {
    invited_by?: {
      id: string;
      email: string;
      username?: string;
      name?: string;
    };
    user_id?: {
      id: string;
      email: string;
      username?: string;
      name?: string;
    };
  };
}

export interface TodoList {
  id: string;
  user_id: string;
  name: string;
  color: string;
  createdAt: string;
  pinned?: boolean;
  archived?: boolean;
  yjsUpdate?: string;
  deleted?: boolean;
  readOnly?: boolean;
  // True when the current user is NOT the original owner of the list
  // (derived in runtime; optional to avoid breaking older objects)
  shared?: boolean;
}

export interface TodoListWithTodos extends TodoList {
  todos: Todo[];
}